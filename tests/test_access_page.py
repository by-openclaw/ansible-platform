"""docs/access.md ("how do I get in") is generated for people and lives in a public repository.

It must name no real domain and no address, and it must be the page the data produces: a
service that gets a login or a group shows up without anybody editing the page.
"""

from __future__ import annotations

import pathlib
import re

import pytest

yaml = pytest.importorskip("yaml")

ROOT = pathlib.Path(__file__).resolve().parents[1]
ALL = ROOT / "inventories" / "prod" / "group_vars" / "all"
PAGE = (ROOT / "docs" / "access.md").read_text()
IDENTITY = yaml.safe_load((ALL / "identity.yml").read_text())
DOMAIN = re.search(r'^platform_domain:\s*"([^"]+)"', (ALL / "deployment.yml").read_text(), re.M).group(1)


def test_no_real_domain_and_no_address():
    assert DOMAIN not in PAGE
    assert not re.search(r"\b\d{1,3}(\.\d{1,3}){3}\b", PAGE)
    assert "<domain>" in PAGE


def test_it_is_generated_not_written():
    assert PAGE.startswith("<!-- GENERATED by playbooks/register.yml")


def test_every_declared_login_is_on_the_page_with_its_group():
    for service, paths in IDENTITY["platform_service_logins"].items():
        row = next((line for line in PAGE.splitlines() if line.startswith(f"| {service} |")), None)
        assert row, f"{service} has a login in the inventory but no row on the page — run playbooks/register.yml"
        assert IDENTITY["platform_service_groups"][service]["admin"] in row
        for path in paths:
            assert f"secret/<env>/{path}" in row


def test_no_login_on_the_page_that_the_inventory_does_not_declare():
    declared = {p for paths in IDENTITY["platform_service_logins"].values() for p in paths}
    on_page = set(re.findall(r"`secret/<env>/([a-z0-9-]+/[a-z0-9-]+)`", PAGE))
    assert on_page == declared
